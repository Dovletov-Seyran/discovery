// Ограничение частоты кадров. Браузер зовёт requestAnimationFrame с частотой экрана — на MacBook Pro
// это 120 Гц, и видеокарта без остановки рисует 120 кадров в секунду: ноут греется, а глазу хватает 60.
// Лишние вызовы пропускаем; запас 2 мс — чтобы 60 Гц-экран не терял кадры из-за дрожания таймера.
export const FPS_PLAY = 60;   // игра
export const FPS_CALM = 30;   // меню, диалог, журнал: игрок читает, сцена почти не меняется

export function frameDue(now, last, fps) {
  return last == null || now - last >= 1000 / fps - 2;
}
